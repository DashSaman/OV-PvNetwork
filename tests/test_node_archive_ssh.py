"""Actual pinned loopback SSH and root helper bytes in a disposable Linux runner."""
import hashlib
import os
from pathlib import Path
import secrets
import socket
import subprocess
import tempfile
import threading
import unittest
from unittest.mock import patch

import paramiko


@unittest.skipUnless(os.name=='posix' and os.geteuid()==0,'dedicated root-owned Linux SSH fixture required')
class NodeArchiveSshTests(unittest.TestCase):
    def test_real_pinned_SSH_delivers_only_verified_private_archive(self):
        from backend.node import archive_transport,native_deploy
        from backend import security_ssh
        from backend.security_ssh import sha256_fingerprint
        folder=tempfile.TemporaryDirectory();root=Path(folder.name)
        backups=Path('/var/backups/pvnetwork-node');created=not backups.exists();backups.mkdir(mode=0o700,exist_ok=True)
        path=backups/('20261015-150000-'+secrets.token_hex(6)+'.tar.gz')
        data=b'private-loopback-SSH-archive-fixture';path.write_bytes(data);path.chmod(0o600)
        receipt={'state':'backup_verified','restore_verified':True,'path':str(path),'size':len(data),'sha256':hashlib.sha256(data).hexdigest()}
        hostkey=paramiko.RSAKey.generate(2048);listener=socket.socket();listener.bind(('127.0.0.1',0));listener.listen(1);listener.settimeout(10)
        port=listener.getsockname()[1];finished=threading.Event();errors=[];auth=[]
        class Server(paramiko.ServerInterface):
            def check_auth_password(self,username,password):
                auth.append(username)
                return paramiko.AUTH_SUCCESSFUL if username=='root' and password=='loopback-fixture-password' else paramiko.AUTH_FAILED
            def get_allowed_auths(self,username):return 'password'
            def check_channel_request(self,kind,channel_id):return paramiko.OPEN_SUCCEEDED if kind=='session' else paramiko.OPEN_FAILED_ADMINISTRATIVELY_PROHIBITED
            def check_channel_exec_request(self,channel,command):
                def execute():
                    try:
                        header=channel.makefile('rb').readline(4097)
                        # This loopback test runs the exact fixed helper command
                        # generated by the client, including its real root scope.
                        result=subprocess.run(command.decode(),shell=True,input=header,capture_output=True,timeout=15)
                        if result.stdout:channel.sendall(result.stdout)
                        if result.stderr:channel.send_stderr(result.stderr)
                        channel.send_exit_status(result.returncode);channel.shutdown_write()
                    except Exception as error:errors.append(error)
                    finally:finished.set()
                threading.Thread(target=execute,daemon=True).start();return True
        def serve():
            transport=None
            try:
                connection,_=listener.accept();transport=paramiko.Transport(connection);transport.add_server_key(hostkey);transport.start_server(server=Server())
                channel=transport.accept(10)
                if channel is None:raise AssertionError('loopback session not opened')
                if not finished.wait(20):raise AssertionError('loopback helper did not finish')
            except Exception as error:errors.append(error)
            finally:
                if transport:transport.close()
        worker=threading.Thread(target=serve,daemon=True);worker.start();client=None
        try:
            with patch.object(security_ssh,'KNOWN_HOSTS_PATH',root/'known_hosts'):
                client=native_deploy.connect('127.0.0.1',port,'root',password='loopback-fixture-password',fingerprint=sha256_fingerprint(hostkey))
                result=archive_transport.download_archive(client,'root',receipt,root/'download.tar.gz')
            self.assertEqual((root/'download.tar.gz').read_bytes(),data)
            self.assertEqual(result['sha256'],receipt['sha256'])
            self.assertEqual(auth,['root'])
            self.assertEqual(path.read_bytes(),data)
            self.assertEqual((root/'download.tar.gz').stat().st_mode&0o777,0o600)
        finally:
            if client:client.close()
            listener.close();worker.join(timeout=20)
            path.unlink()
            if created:backups.rmdir()
            folder.cleanup()
        self.assertFalse(worker.is_alive())
        self.assertEqual(errors,[])
